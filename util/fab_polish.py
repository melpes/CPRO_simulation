"""v2 docx 에서 되돌린 md 를 다듬는다.

① 체크리스트 말투를 "~인가?" → "~인지" 로 통일
② 로그 실측 절을 무엇을 어떻게 알아냈고 무엇을 뜻하는지로 다시 씀
③ 프린팅 용도 절에 "왜 두 종류인가"(재료 점도) 를 넣음
"""
import re

BASE = r"C:/Users/KangTaehui/KG/keti/CPRO_조립공정/시뮬레이션/Package/docs/FAB"
SRC = f"{BASE}/_v2.md"
OUT = f"{BASE}/핵심공정선정_방문자료.md"

s = open(SRC, encoding="utf-8").read()

# ── pandoc 이스케이프 정리 ──────────────────────────────────────────────
s = s.replace(r"\-", "-").replace(r"\~", "~").replace(r"\#", "#")
s = s.replace("GLASS\\_MOVEMENT", "GLASS_MOVEMENT").replace("ASHING\\_O2\\_60s", "ASHING_O2_60s")
s = re.sub(r"``\s*``", " ", s)                       # `디스플레이`` ``패터닝` 형태 복구
s = re.sub(r"``", "", s)
s = re.sub(r"^#{1,3}\s*$\n\n", "", s, flags=re.M)

# ── ① 체크리스트 말투 통일 ──────────────────────────────────────────────
END = {
    "맞는가": "맞는지", "있는가": "있는지", "없는가": "없는지",
    "하는가": "하는지", "되는가": "되는지", "쓰는가": "쓰는지",
    "가능한가": "가능한지", "인가": "인지", "운영되는가": "운영되는지",
    "남는가": "남는지", "걸리는가": "걸리는지", "옮기는가": "옮기는지",
    "따로 있는가": "따로 있는지", "볼 수 있는가": "볼 수 있는지",
    "서 있는가": "서 있는지", "사용되는가": "사용되는지",
    "개정본인가": "개정본인지", "오류인가": "오류인지",
    "몇 분인가": "몇 분인지", "무엇인가": "무엇인지",
    "이유는 무엇인가": "이유",
}
lines = s.split("\n")
for i, ln in enumerate(lines):
    if not ln.lstrip().startswith(("- [ ]", "-   [ ]", "[ ]")):
        continue
    t = ln.rstrip()
    t = re.sub(r"\?$", "", t).rstrip()
    for a, b in sorted(END.items(), key=lambda x: -len(x[0])):
        if t.endswith(a):
            t = t[: -len(a)] + b
            break
    lines[i] = t
s = "\n".join(lines)

# ── ② 로그 실측 ────────────────────────────────────────────────────────
a = s.index("## 로그 실측")
b = s.index("## 용어")
s = s[:a] + """## 로그 실측 — 박막증착장비 5개월치에서 확인한 것

로그로 알 수 있는 것은 **기판이 챔버를 얼마나 점유했는지**와 **설비가 언제 돌았는지** 두 가지다.
공정 조건(파워·가스·시간)은 runsheet 에 있으므로, 로그는 그 조건이 실제로 얼마나 걸렸는지를 보여준다.

### 챔버 점유 시간 = 레시피 시간 + 약 92초

레시피 이름에 공정 시간이 들어 있어(`CF4_O2_600W_60s`) 실제 점유 시간과 대조가 가능했다.
Dry etcher 128런·PECVD 72런 전부에서 **차이가 91~93초로 일정**했다.

| 레시피 | 레시피상 시간 | 실제 점유 | 차이 |
|---|---|---|---|
| `Mo_S.D_250_500_20s` | 20 s | 112 s | +92 |
| `CF4_O2_600W_60s` | 60 s | 152 s | +92 |
| `Cl2_Ar_O2_220s` | 220 s | 311 s | +91 |
| `MO_400W_360S` | 360 s | 452 s | +92 |

92초는 기판을 넣고 진공을 잡고 빼는 데 드는 고정 시간으로 보인다.
→ **시뮬의 설비 점유 시간은 `runsheet 공정시간 + 92초` 로 잡을 수 있다.**

### 설비는 거의 놀고 있다

| | |
|---|---|
| 설비 가동률 | **4~7%** — 5개월 중 실제로 공정이 돈 시간의 비율 |
| 런 간격 | 중앙값 **약 15분** — 한 런이 끝나고 다음 런까지 |
| 챔버 간 반송 | 13~19초 |
| 로드락 (대기압↔진공) | 약 4분 |

### 병목은 설비가 아니라 작업자

| | |
|---|---|
| 17시 이후 | 실행 **0건** |
| 주말 | 실행 **0건** |
| 12시대 | 공백 (점심) |

설비는 무인으로도 돌 수 있으나 **근무시간에만 가동**된다.
반송이 13~19초로 빠르고 가동률이 4~7%인데도 처리량이 낮은 이유가 여기 있다.
→ **작업자 인원·근무시간이 처리량을 결정한다.** CPRO 조립공정과 같은 구조

""" + s[b:]

# ── ③ 프린팅 용도 — 왜 두 종류인가 ──────────────────────────────────────
a = s.index("### 용도 (장비리스트 원문)")
b = s.index("# Ⅲ. 상세")
s = s[:a] + """### 왜 두 종류인가 — 재료 점도가 방식을 가른다

같은 "인쇄"지만 **다룰 수 있는 재료의 묽기가 1만 배 차이**라 한 장비로 둘 다 못 한다.

| | 스크린 | 잉크젯 |
|---|---|---|
| 재료 점도 | **30,000 ~ 200,000 cps** (치약·꿀 수준) | **1 ~ 20 cPs** (물 수준) |
| 재료를 내보내는 법 | 제판 구멍으로 스퀴지가 **밀어넣음** | 노즐에서 액적으로 **뿌림** |
| 결과 | 두껍게 · 거칠게 | 얇게 · 정밀하게 |
| 만드는 것 | 전극 · 배선 · **격벽** | **발광층** · 컬러필터 등 기능층 |

걸쭉한 페이스트는 노즐을 막아 잉크젯으로 못 쓰고, 묽은 잉크는 제판 구멍으로 흘러내려 스크린으로 못 쓴다.
**만들려는 것이 두꺼운 구조물이냐 얇은 기능층이냐로 갈린다.**

컬러필터는 양쪽에 다 나오는데, **스크린이 격벽(칸막이)을 찍고 잉크젯이 그 안에 색을 채우는** 역할 분담으로 보인다.

### 용도 (장비리스트 원문)

**스크린프린터** (Seria SSA-GL4737-RST) — `디스플레이 패터닝 공정 개발 (격벽 C/F 등)`

**잉크젯 프린터 4대** — 대면적 2대 / 평가용 2대

| 장비 | 제작사 | 용도 |
|---|---|---|
| for PLED #1 | Litrex 120L | LCD Color Filter 패터닝 · CF 잉크 평가 · EL 패터닝 |
| for PLED #2 | Ulvac | 〃 + vision align 정밀 위치 제어 |
| lab | Fuji Film DMP-2831 | PLED/OLED **발광층** · Color Filter · 전도성 잉크 |
| lab #2 | Dimatix | 유/무기 EL 잉크 **특성 평가** |

Dimatix 사양에 `잉크젯 대면적 프린팅 이전에 본 장비로 잉크 특성 평가 확인 후 대면적 장비에 적용` 명시
→ **소량으로 잉크를 시험하고 검증되면 대면적 장비로 본 인쇄**하는 구조.
`lab` 이 붙은 2대가 평가용, 나머지 2대가 실제 생산용

잉크젯 설명에 `전통적 방식의 Photolithography를 대체할 수 있는` 이라고 기재되어 있음

""" + s[b:]

open(OUT, "w", encoding="utf-8").write(s)
print("적용 완료 :", len(s), "자")
