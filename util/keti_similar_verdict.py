import re as _re


def _bare(name):
    """앞의 '01_' 같은 일련번호를 뗀다. 유사장비가 추가되면 번호가 밀리기 때문이다."""
    return _re.sub(r"^\d{2}_", "", name).strip()


def verdict_of(aas, filename):
    """파일 하나의 등급을 찾는다. 사용자 판단이 있으면 그것을 우선한다."""
    fn = _bare(filename)
    for (a, pre), (g, why) in USER_GRADE.items():
        if a == aas and fn.startswith(_bare(pre)):
            return g, why
    for a, pre, v, why in VERDICT:
        if a == aas and fn.startswith(_bare(pre)):
            return FALLBACK.get(v, v), why
    return "미판정", ""
